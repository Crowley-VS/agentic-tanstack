#!/usr/bin/env node
// Opt-in: Playwright's Test Agents (planner, generator, healer) as Claude Code subagents, for this
// repo's e2e project (docs/agents.md).
//
//   pnpm pw:agents              generate them (again: it overwrites them)
//   pnpm pw:agents --mcp-json   also put their MCP server in .mcp.json, for the main session
//
// It runs the pinned Playwright's `playwright init-agents --loop=claude -c <CONFIG>` from the repo
// root, then:
// - patches each agent it wrote (.claude/agents/playwright-test-*.md) to start the playwright-test
//   MCP server itself (`mcpServers` in its frontmatter): the pinned Playwright's CLI run by node
//   (not npx, and not `pnpm exec`, whose own output on stdout would break the MCP protocol), this
//   repo's config and `--headless`. Paths are relative: Claude Code starts it in the session's
//   directory, the repo root;
// - puts .mcp.json back as it was, or deletes it when there was none: init-agents overwrites it
//   with an npx server for every session. With --mcp-json it keeps the servers .mcp.json had and
//   adds the patched one; when .mcp.json is not JSON, it leaves it alone and exits 1.
// What it generates stays on this machine: .gitignore lists the agents, specs/ (the planner's
// test plans) and .mcp.json. Plain Node, no dependencies.
import { spawnSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const CONFIG = 'apps/web-e2e/playwright.config.mts';
export const SERVER = 'playwright-test';
const AGENTS_DIR = '.claude/agents';
const GENERATED = /^playwright-test-[\w-]+\.md$/;
export const USAGE = `Usage: pnpm pw:agents [--mcp-json]

Generates Playwright's test agents (planner, generator, healer) into .claude/agents for
${CONFIG}, patched to run the pinned Playwright headless. Local only (.gitignore).
  --mcp-json   also add their MCP server to .mcp.json (otherwise .mcp.json is left as it was)`;

/** The Playwright CLI the MCP server runs, relative to the repo root (root devDependency). */
export const CLI = 'node_modules/@playwright/test/cli.js';

/** The playwright-test MCP server: the pinned Playwright, this repo's config, headless. */
export const MCP_SERVER = {
  type: 'stdio',
  command: 'node',
  args: [CLI, 'run-test-mcp-server', '--headless', '-c', CONFIG],
};

/**
 * `text` (a generated agent) with the MCP server in its frontmatter and a note after it, or
 * undefined when it has no frontmatter. The server is defined in the agent, so its tools
 * (`mcp__playwright-test__…`) exist only while the agent runs.
 */
export function patchAgent(text, server = MCP_SERVER) {
  const m = text.match(/^---\r?\n([\s\S]*?\r?\n)---\r?\n/);
  if (!m) return undefined;
  const frontmatter = m[1].replace(/^mcpServers:\n(?:[ \t]+.*\n)*/m, '');
  const block = [
    'mcpServers:',
    `  - ${SERVER}:`,
    `      type: ${server.type}`,
    `      command: ${server.command}`,
    `      args: ${JSON.stringify(server.args)}`,
    '',
  ].join('\n');
  const note = `<!-- Generated by \`pnpm pw:agents\` (playwright init-agents), then patched: the ${SERVER} MCP server above runs the pinned Playwright headless with ${CONFIG}. Local to this machine (.gitignore); run \`pnpm pw:agents\` again after a Playwright bump. -->\n`;
  const body = text.slice(m[0].length).replace(/^<!-- Generated by `pnpm pw:agents`[^\n]*\n/, '');
  return `---\n${frontmatter}${block}---\n${note}${body}`;
}

/** `[node, playwright's cli]` installed at `root`, or undefined before `pnpm install`. */
export function playwrightBin(root = ROOT) {
  const dir = join(root, 'node_modules', '@playwright', 'test');
  try {
    const { bin } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const entry = typeof bin === 'string' ? bin : bin?.playwright;
    return entry && existsSync(join(dir, entry)) ? [process.execPath, join(dir, entry)] : undefined;
  } catch {
    return undefined;
  }
}

const read = (file) => (existsSync(file) ? readFileSync(file, 'utf8') : undefined);

/** Run it; returns the exit code. `playwright`: `[command, ...args]` that runs the Playwright CLI. */
export function main(
  argv,
  { root = ROOT, playwright = playwrightBin(root), log = console.log } = {},
) {
  if (argv.includes('-h') || argv.includes('--help')) {
    log(USAGE);
    return 0;
  }
  if (argv.some((a) => a !== '--mcp-json')) {
    console.error(`✗ pw:agents: unknown argument\n\n${USAGE}`);
    return 2;
  }
  const mcpJson = argv.includes('--mcp-json');
  if (!existsSync(join(root, CONFIG))) {
    console.error(`✗ pw:agents: ${CONFIG} not found`);
    return 1;
  }
  if (!playwright) {
    console.error('✗ pw:agents: Playwright is not installed: run `pnpm install`');
    return 1;
  }

  const mcpFile = join(root, '.mcp.json');
  const mcpBefore = read(mcpFile);
  const specsBefore = existsSync(join(root, 'specs'));
  const [cmd, ...pre] = playwright;
  const args = [...pre, 'init-agents', '--loop=claude', '-c', CONFIG];
  log(`pw:agents: playwright ${args.slice(pre.length).join(' ')}`);
  const res = spawnSync(cmd, args, { cwd: root, stdio: 'inherit' });

  const done = [];
  // --mcp-json asked for a server that could not be added: the run fails once the agents are done
  let mcpFailed = false;
  // .mcp.json: as it was, unless --mcp-json; whatever init-agents did, even when it failed
  const mcpAfter = read(mcpFile);
  if (mcpJson && res.status === 0) {
    let config = {};
    try {
      config = mcpBefore ? JSON.parse(mcpBefore) : {};
    } catch {
      config = undefined;
    }
    if (config) {
      config.mcpServers = { ...config.mcpServers, [SERVER]: MCP_SERVER };
      writeFileSync(mcpFile, `${JSON.stringify(config, null, 2)}\n`);
      done.push(`.mcp.json: added the ${SERVER} server (pinned Playwright, headless)`);
    } else {
      if (mcpAfter !== mcpBefore) writeFileSync(mcpFile, mcpBefore);
      mcpFailed = true;
      console.error(
        `✗ pw:agents: .mcp.json is not JSON: left as it was, without the ${SERVER} server`,
      );
      done.push(
        `.mcp.json: not JSON, so the ${SERVER} server was not added (left as it was): fix it, then run \`pnpm pw:agents --mcp-json\` again`,
      );
    }
  } else if (mcpAfter !== mcpBefore) {
    if (mcpBefore === undefined) rmSync(mcpFile, { force: true });
    else writeFileSync(mcpFile, mcpBefore);
    done.push(
      `.mcp.json: init-agents ${mcpBefore === undefined ? 'created' : 'overwrote'} it; put back as it was`,
    );
  }
  if (res.status !== 0) {
    console.error(`✗ pw:agents: playwright init-agents failed (exit ${res.status ?? res.signal})`);
    for (const line of done) log(`  ${line}`);
    return res.status || 1;
  }

  const dir = join(root, AGENTS_DIR);
  const agents = existsSync(dir) ? readdirSync(dir).filter((f) => GENERATED.test(f)) : [];
  for (const file of agents.toSorted()) {
    const path = join(dir, file);
    const patched = patchAgent(readFileSync(path, 'utf8'), MCP_SERVER);
    if (!patched) {
      console.error(`✗ pw:agents: ${AGENTS_DIR}/${file} has no frontmatter: not patched`);
      return 1;
    }
    writeFileSync(path, patched);
    done.push(`${AGENTS_DIR}/${file}: patched (its own ${SERVER} server, headless)`);
  }
  if (!agents.length) {
    console.error(`✗ pw:agents: init-agents wrote no ${AGENTS_DIR}/playwright-test-*.md`);
    return 1;
  }
  if (!specsBefore && existsSync(join(root, 'specs')))
    done.push('specs/: created for the test plans (gitignored)');

  log(
    [
      '',
      'pw:agents:',
      ...done.map((line) => `  - ${line}`),
      '',
      'Local to this machine: .gitignore lists them. They load in the next Claude Code session',
      'started at the repo root, after you trust the folder; each call to their MCP tools asks',
      'first unless you allow it. Run it again after a Playwright bump.',
    ].join('\n'),
  );
  return mcpFailed ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  process.exitCode = main(process.argv.slice(2));
