// scripts/pw-agents.mjs (`pnpm pw:agents`): with a fake `playwright init-agents` that writes what
// Playwright 1.63 writes, and once with the real one in a throwaway copy of the repository.
import { execFileSync, spawn } from 'node:child_process';
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { afterEach, beforeEach, describe, expect, it, onTestFinished, vi } from 'vitest';
import { CLI, CONFIG, main, MCP_SERVER, patchAgent, playwrightBin } from '../pw-agents.mjs';

const REPO = resolve(import.meta.dirname, '../..');
const NAMES = ['generator', 'healer', 'planner'];

// What `playwright init-agents --loop=claude` writes (1.63): an agent per role, an npx MCP server in
// .mcp.json (overwriting it) and specs/README.md when there is no specs/.
const FAKE = `import { appendFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
appendFileSync(process.env.FAKE_PW_LOG, JSON.stringify({ argv: process.argv.slice(2), cwd: process.cwd() }) + '\\n');
if (process.env.FAKE_PW_STATUS) {
  writeFileSync('.mcp.json', '{"broken": true}');
  process.exit(Number(process.env.FAKE_PW_STATUS));
}
if (!existsSync('specs')) {
  mkdirSync('specs');
  writeFileSync('specs/README.md', '# Specs\\n');
}
mkdirSync('.claude/agents', { recursive: true });
for (const name of ${JSON.stringify(NAMES)})
  writeFileSync('.claude/agents/playwright-test-' + name + '.md', [
    '---',
    'name: playwright-test-' + name,
    'description: Use this agent when you need to ' + name,
    'tools: Glob, Grep, Read, LS, mcp__playwright-test__browser_snapshot, mcp__playwright-test__test_run',
    'model: sonnet',
    'color: green',
    '---',
    '',
    'You are the ' + name + '.',
  ].join('\\n'));
writeFileSync('.mcp.json', JSON.stringify({ mcpServers: { 'playwright-test': { command: 'npx', args: ['playwright', 'run-test-mcp-server'] } } }, null, 2));
`;

let tmp;
let log;
let fake;
beforeEach(() => {
  tmp = mkdtempSync(join(tmpdir(), 'pw-agents-'));
  onTestFinished(() => rmSync(tmp, { recursive: true, force: true }));
  log = join(tmp, 'pw.log');
  fake = join(tmp, 'fake-playwright.mjs');
  writeFileSync(fake, FAKE);
  vi.stubEnv('FAKE_PW_LOG', log);
  vi.spyOn(console, 'error').mockImplementation(() => {});
});
afterEach(() => {
  vi.unstubAllEnvs();
  vi.restoreAllMocks();
});

/** A checkout with the e2e config (and `files`), and pw:agents run in it with the fake. */
function run(argv = [], files = {}) {
  const root = join(tmp, 'repo');
  for (const [path, text] of Object.entries({ [CONFIG]: '', ...files })) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
  const out = [];
  const code = main(argv, {
    root,
    playwright: [process.execPath, fake],
    log: (line) => out.push(line),
  });
  const calls = existsSync(log)
    ? readFileSync(log, 'utf8')
        .split('\n')
        .filter(Boolean)
        .map((l) => JSON.parse(l))
    : [];
  const read = (path) =>
    existsSync(join(root, path)) ? readFileSync(join(root, path), 'utf8') : undefined;
  return { code, root, out: out.join('\n'), calls, read };
}

describe('pw:agents', () => {
  it('runs init-agents for the e2e config from the repo root, and patches every agent', () => {
    const res = run();
    expect(res.code, res.out).toBe(0);
    expect(res.calls).toEqual([
      { argv: ['init-agents', '--loop=claude', '-c', CONFIG], cwd: res.root },
    ]);
    for (const name of NAMES) {
      const text = res.read(`.claude/agents/playwright-test-${name}.md`);
      expect(text?.split('\n')).toEqual([
        '---',
        `name: playwright-test-${name}`,
        `description: Use this agent when you need to ${name}`,
        'tools: Glob, Grep, Read, LS, mcp__playwright-test__browser_snapshot, mcp__playwright-test__test_run',
        'model: sonnet',
        'color: green',
        'mcpServers:',
        '  - playwright-test:',
        '      type: stdio',
        '      command: node',
        `      args: ["${CLI}","run-test-mcp-server","--headless","-c","${CONFIG}"]`,
        '---',
        expect.stringMatching(/^<!-- Generated by `pnpm pw:agents`.* -->$/),
        '',
        `You are the ${name}.`,
      ]);
    }
    expect(res.out).toContain('specs/: created for the test plans (gitignored)');
  });

  it('deletes the .mcp.json init-agents created', () => {
    const res = run();
    expect(res.read('.mcp.json')).toBeUndefined();
    expect(res.out).toContain('.mcp.json: init-agents created it; put back as it was');
  });

  it('puts back, byte for byte, the .mcp.json init-agents overwrote', () => {
    const mine = '{ "mcpServers": { "mine": { "command": "true" } } }\n';
    const res = run([], { '.mcp.json': mine });
    expect(res.read('.mcp.json')).toBe(mine);
    expect(res.out).toContain('.mcp.json: init-agents overwrote it; put back as it was');
  });

  it('--mcp-json: keeps the servers .mcp.json had and adds the patched one', () => {
    const res = run(['--mcp-json'], {
      '.mcp.json': '{ "mcpServers": { "mine": { "command": "true" } } }\n',
    });
    expect(JSON.parse(res.read('.mcp.json') ?? '')).toEqual({
      mcpServers: { mine: { command: 'true' }, 'playwright-test': MCP_SERVER },
    });
    // a .mcp.json that is not JSON is left as it was
    const broken = run(['--mcp-json'], { '.mcp.json': '{ not json' });
    expect(broken.read('.mcp.json')).toBe('{ not json');
  });

  it('when init-agents fails: puts .mcp.json back, patches nothing and exits non-zero', () => {
    vi.stubEnv('FAKE_PW_STATUS', '3');
    const res = run([], { '.mcp.json': '{}\n' });
    expect(res.code).toBe(3);
    expect(res.read('.mcp.json')).toBe('{}\n');
    expect(existsSync(join(res.root, '.claude/agents'))).toBe(false);
  });

  it('refuses unknown arguments and a checkout without the e2e config', () => {
    expect(run(['--yes']).code).toBe(2);
    expect(main([], { root: tmp, playwright: [process.execPath, fake] })).toBe(1);
    expect(existsSync(log)).toBe(false);
  });

  it('patches an agent once, however often it runs', () => {
    const agent = '---\nname: a\n---\n\nBody\n';
    const once = patchAgent(agent);
    expect(patchAgent(once ?? '')).toBe(once);
    expect(patchAgent('no frontmatter')).toBeUndefined();
  });

  it('runs the CLI this repo installs, and git ignores what it generates', () => {
    expect(playwrightBin(REPO)?.[1]).toBe(join(REPO, CLI));
    expect(existsSync(join(REPO, CONFIG))).toBe(true);
    const ignored = execFileSync(
      'git',
      ['check-ignore', '--no-index', '.claude/agents/playwright-test-planner.md', 'specs/plan.md'],
      { cwd: REPO, encoding: 'utf8' },
    );
    expect(ignored.trim().split('\n')).toEqual([
      '.claude/agents/playwright-test-planner.md',
      'specs/plan.md',
    ]);
  });
});

/** The tool names the MCP server started like `server` in `cwd` lists. */
async function serverTools(server, cwd) {
  const child = spawn(server.command, server.args, { cwd, stdio: ['pipe', 'pipe', 'ignore'] });
  try {
    let buf = '';
    const replies = new Map();
    child.stdout.on('data', (d) => {
      buf += d;
      for (let i = buf.indexOf('\n'); i !== -1; i = buf.indexOf('\n')) {
        const line = buf.slice(0, i);
        buf = buf.slice(i + 1);
        // anything but JSON on stdout breaks the protocol (`pnpm exec` printed its own lines)
        const msg = JSON.parse(line);
        replies.get(msg.id)?.(msg);
      }
    });
    let id = 0;
    const call = (method, params) =>
      new Promise((done) => {
        replies.set(++id, done);
        child.stdin.write(`${JSON.stringify({ jsonrpc: '2.0', id, method, params })}\n`);
      });
    await call('initialize', {
      protocolVersion: '2025-06-18',
      capabilities: {},
      clientInfo: { name: 'test', version: '0' },
    });
    child.stdin.write(
      `${JSON.stringify({ jsonrpc: '2.0', method: 'notifications/initialized' })}\n`,
    );
    const { result } = await call('tools/list', {});
    return new Set(result.tools.map((t) => `mcp__playwright-test__${t.name}`));
  } finally {
    child.kill();
  }
}

describe('the real init-agents (a throwaway copy of the repository)', () => {
  it('writes agents whose patched server serves every tool they name, and no .mcp.json', async () => {
    const copy = join(tmp, 'copy');
    const files = execFileSync('git', ['ls-files', '-co', '--exclude-standard', '-z'], {
      cwd: REPO,
      encoding: 'utf8',
    })
      .split('\0')
      .filter((f) => f && existsSync(join(REPO, f)));
    for (const f of files) {
      mkdirSync(dirname(join(copy, f)), { recursive: true });
      cpSync(join(REPO, f), join(copy, f));
    }
    // the installed packages, shared: the root's and each project's
    for (const dir of new Set([
      '.',
      ...files.filter((f) => f.endsWith('package.json')).map(dirname),
    ]))
      if (existsSync(join(REPO, dir, 'node_modules')))
        symlinkSync(join(REPO, dir, 'node_modules'), join(copy, dir, 'node_modules'), 'junction');
    execFileSync('git', ['init', '-q', '-b', 'main'], { cwd: copy }); // tools/dev-ports.mjs needs one

    const out = [];
    expect(main([], { root: copy, log: (l) => out.push(l) }), out.join('\n')).toBe(0);
    expect(existsSync(join(copy, '.mcp.json'))).toBe(false);
    const agents = readdirSync(join(copy, '.claude/agents')).filter((f) =>
      f.startsWith('playwright-test-'),
    );
    expect(agents.toSorted()).toEqual(NAMES.map((n) => `playwright-test-${n}.md`));

    const tools = await serverTools(MCP_SERVER, copy);
    for (const file of agents) {
      const text = readFileSync(join(copy, '.claude/agents', file), 'utf8');
      expect(text).toContain(`      args: ${JSON.stringify(MCP_SERVER.args)}\n`);
      const named = (text.match(/^tools: (.*)$/m)?.[1] ?? '')
        .split(', ')
        .filter((t) => t.startsWith('mcp__'));
      expect(named.length, file).toBeGreaterThan(0);
      expect(
        named.filter((t) => !tools.has(t)),
        file,
      ).toEqual([]);
    }
  }, 120_000);
});
